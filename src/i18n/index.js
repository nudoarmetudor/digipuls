/**
 * Returns a translate function for one language.
 *
 * t('key')                       -> the string
 * t('key', { n: 3 })             -> the string with {n} replaced by 3
 *
 * A key missing from the requested language falls back to English rather than
 * rendering blank; a key missing everywhere renders as the key itself, which
 * is ugly on purpose so it gets noticed in review.
 */
function t(lang) {
  const dict = STRINGS[lang] || STRINGS.en;
  return (key, params) => {
    const raw = dict[key] !== undefined ? dict[key] : (STRINGS.en[key] !== undefined ? STRINGS.en[key] : key);
    if (!params) return raw;
    return raw.replace(/\{(\w+)\}/g, (match, name) =>
      (params[name] !== undefined ? String(params[name]) : match));
  };
}

/**
 * Best supported language for an Accept-Language header, defaulting to
 * English. Only used for a visitor who has never chosen one — an explicit
 * choice (session or cookie) always wins over what the browser says.
 *
 * "mo" is accepted as an alias for Romanian: it is the deprecated ISO code
 * for Moldovan, and some older systems and browser builds in the country
 * still send it.
 */
function pickFromAcceptLanguage(header) {
  if (!header) return 'en';
  const ranked = String(header)
    .split(',')
    .map((part) => {
      const [tag, ...params] = part.trim().split(';');
      const q = params.map((p) => p.trim()).find((p) => p.startsWith('q='));
      return { tag: tag.trim().toLowerCase(), q: q ? parseFloat(q.slice(2)) : 1 };
    })
    .filter((entry) => entry.tag && !Number.isNaN(entry.q) && entry.q > 0)
    .sort((a, b) => b.q - a.q);

  for (const { tag } of ranked) {
    const base = tag.split('-')[0];
    if (base === 'mo') return 'ro';
    if (SUPPORTED_LANGS.includes(base)) return base;
  }
  return 'en';
}

