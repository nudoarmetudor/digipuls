// UI translation dictionary for the three languages DigiPuls ships in:
// English, Romanian (the state language) and Russian (the largest minority
// language of instruction in Moldova, and the working language of a
// substantial share of schools in the north and in Gagauzia/Transnistria-
// adjacent districts).
//
// Two rules keep this honest:
//   * Every key exists in all three dictionaries. tests/i18n.test.js fails
//     the build if one drifts, so a new key can't quietly ship as English
//     text inside a Russian page.
//   * Views never inline a language conditional. Anything a person reads
//     goes through t(); the old `lang === 'ro' ? ... : ...` pattern silently
//     served English to Russian readers, which is exactly the failure mode
//     the test above now catches.
//
// Indicator/domain/level *content* — the assessment instrument itself — lives
// in src/data/indicators.{js,ro,ru}.js. This file is everything around it.

